//! Biometric authentication & unlock protocol primitives (protocol §11).
//!
//! Provides the signed challenge-response messages used to unlock Windows
//! from a paired Android phone via hardware-backed BiometricPrompt / Keystore.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::DeviceId;

/// Domain separation label for unlock signature payload.
pub const UNLOCK_PAYLOAD_LABEL: &[u8] = b"linkroid-auth-unlock-v1";
/// Domain separation label for lock signature payload.
pub const LOCK_PAYLOAD_LABEL: &[u8] = b"linkroid-auth-lock-v1";

/// Standard challenge validity window (30 seconds).
pub const CHALLENGE_TTL_SECS: u64 = 30;

/// Sent by PC to phone when an unlock flow is initiated at LogonUI.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UnlockChallenge {
    /// 32-byte cryptographically secure random nonce.
    #[serde(with = "serde_bytes")]
    pub nonce: Vec<u8>,
    /// Unique session / attempt identifier.
    pub session_id: String,
    /// PC's DeviceId, preventing cross-device relay attacks.
    pub pc_id: DeviceId,
    /// Expiration timestamp in seconds (Unix epoch).
    pub expiry: u64,
}

/// Returned by phone upon successful BiometricPrompt authentication.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UnlockResponse {
    /// Matches the challenge's session_id.
    pub session_id: String,
    /// Timestamp at which biometric prompt succeeded (Unix epoch seconds).
    pub timestamp: u64,
    /// ECDSA P-256 signature over `canonical_unlock_digest`.
    #[serde(with = "serde_bytes")]
    pub signature: Vec<u8>,
}

/// Sent by phone to remotely lock the PC.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignedLockRequest {
    /// 32-byte single-use nonce generated by phone.
    #[serde(with = "serde_bytes")]
    pub nonce: Vec<u8>,
    /// Target PC's DeviceId.
    pub pc_id: DeviceId,
    /// Request issuance timestamp (Unix epoch seconds).
    pub timestamp: u64,
    /// Optional ECDSA signature if biometric gating is required for lock.
    #[serde(default, skip_serializing_if = "Option::is_none", with = "serde_bytes")]
    pub signature: Option<Vec<u8>>,
}

/// Response acknowledging a lock command.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignedLockResponse {
    pub success: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub message: Option<String>,
}

/// Computes the domain-separated SHA-256 digest for an unlock challenge signature.
pub fn canonical_unlock_digest(
    nonce: &[u8],
    session_id: &str,
    pc_id: &DeviceId,
    timestamp: u64,
) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update(UNLOCK_PAYLOAD_LABEL);
    hasher.update((nonce.len() as u32).to_le_bytes());
    hasher.update(nonce);
    hasher.update((session_id.len() as u32).to_le_bytes());
    hasher.update(session_id.as_bytes());
    hasher.update(pc_id.as_bytes());
    hasher.update(timestamp.to_le_bytes());
    hasher.finalize().into()
}

/// Computes the domain-separated SHA-256 digest for a lock command signature.
pub fn canonical_lock_digest(
    nonce: &[u8],
    pc_id: &DeviceId,
    timestamp: u64,
) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update(LOCK_PAYLOAD_LABEL);
    hasher.update((nonce.len() as u32).to_le_bytes());
    hasher.update(nonce);
    hasher.update(pc_id.as_bytes());
    hasher.update(timestamp.to_le_bytes());
    hasher.finalize().into()
}

/// Inter-Process Communication (IPC) primitives between Windows LogonUI Credential Provider and Linkroid Service.
pub mod ipc {
    use super::*;

    /// Default Windows Named Pipe name for Linkroid Credential Provider IPC.
    pub const AUTH_PIPE_NAME: &str = r"\\.\pipe\LinkroidAuthPipe";

    /// Maximum permitted IPC message size (64 KB) to avoid memory exhaustion.
    pub const MAX_IPC_MESSAGE_SIZE: usize = 65536;

    /// Current IPC protocol version.
    pub const IPC_PROTOCOL_VERSION: u32 = 1;

    /// Request messages sent from LogonUI / Credential Provider DLL / Desktop helper to the Windows Service.
    #[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
    pub enum IpcRequest {
        /// Checks the status of phone pairing and enrollment.
        QueryStatus,
        /// Initiates an unlock challenge-response flow with the enrolled phone.
        StartUnlock,
        /// Polls for the result of an ongoing unlock attempt.
        PollUnlock { session_id: String },
        /// Requests the Windows machine to lock immediately.
        LockWorkStation,
        /// Stores or updates DPAPI-encrypted credentials for auto-logon.
        EnrollCredential {
            username: String,
            domain: Option<String>,
            #[serde(with = "serde_bytes")]
            encrypted_secret: Vec<u8>,
        },
        /// Clears stored credentials and un-enrolls biometric unlock.
        RevokeCredential,
    }

    /// Response messages returned by the Windows Service.
    #[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
    pub enum IpcResponse {
        Status {
            enrolled: bool,
            phone_connected: bool,
            phone_name: Option<String>,
            locked_out: bool,
        },
        UnlockInitiated {
            session_id: String,
            expiry: u64,
        },
        UnlockStatus {
            session_id: String,
            state: UnlockState,
        },
        LockAcknowledged {
            success: bool,
        },
        CredentialEnrolled {
            success: bool,
        },
        CredentialRevoked {
            success: bool,
        },
        Error {
            code: u32,
            message: String,
        },
    }

    /// Status of a pending or completed unlock attempt.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
    pub enum UnlockState {
        Pending,
        Success,
        Denied,
        Expired,
        RateLimited,
    }

    /// Encodes an IPC message into a 4-byte little-endian length-prefixed CBOR payload.
    pub fn encode_ipc_message<T: Serialize>(msg: &T) -> Result<Vec<u8>, String> {
        let mut payload = Vec::new();
        ciborium::into_writer(msg, &mut payload).map_err(|e| e.to_string())?;
        if payload.len() > MAX_IPC_MESSAGE_SIZE {
            return Err("IPC message exceeds maximum permitted size".into());
        }
        let mut framed = Vec::with_capacity(4 + payload.len());
        framed.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        framed.extend_from_slice(&payload);
        Ok(framed)
    }

    /// Decodes an IPC message from a length-prefixed buffer slice.
    pub fn decode_ipc_message<T: for<'de> Deserialize<'de>>(bytes: &[u8]) -> Result<T, String> {
        if bytes.len() < 4 {
            return Err("buffer too short for length prefix".into());
        }
        let len = u32::from_le_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]) as usize;
        if len > MAX_IPC_MESSAGE_SIZE {
            return Err("IPC frame declared length exceeds maximum permitted size".into());
        }
        if bytes.len() < 4 + len {
            return Err("incomplete IPC frame payload".into());
        }
        ciborium::from_reader(&bytes[4..4 + len]).map_err(|e| e.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_ipc_roundtrip_query_status() {
        let req = ipc::IpcRequest::QueryStatus;
        let encoded = ipc::encode_ipc_message(&req).expect("encode query");
        let decoded: ipc::IpcRequest = ipc::decode_ipc_message(&encoded).expect("decode query");
        assert_eq!(req, decoded);

        let resp = ipc::IpcResponse::Status {
            enrolled: true,
            phone_connected: true,
            phone_name: Some("Pixel 9 Pro".into()),
            locked_out: false,
        };
        let encoded_resp = ipc::encode_ipc_message(&resp).expect("encode status");
        let decoded_resp: ipc::IpcResponse =
            ipc::decode_ipc_message(&encoded_resp).expect("decode status");
        assert_eq!(resp, decoded_resp);
    }

    #[test]
    fn test_ipc_roundtrip_lock_command() {
        let req = ipc::IpcRequest::LockWorkStation;
        let encoded = ipc::encode_ipc_message(&req).expect("encode lock");
        let decoded: ipc::IpcRequest = ipc::decode_ipc_message(&encoded).expect("decode lock");
        assert_eq!(req, decoded);

        let resp = ipc::IpcResponse::LockAcknowledged { success: true };
        let encoded_resp = ipc::encode_ipc_message(&resp).expect("encode lock ack");
        let decoded_resp: ipc::IpcResponse =
            ipc::decode_ipc_message(&encoded_resp).expect("decode lock ack");
        assert_eq!(resp, decoded_resp);
    }

    #[test]
    fn test_canonical_unlock_digest_is_deterministic() {
        let pc_id = DeviceId([7u8; 32]);
        let nonce = [1u8; 32];
        let session = "session-12345";
        let time = 1795160000u64;

        let d1 = canonical_unlock_digest(&nonce, session, &pc_id, time);
        let d2 = canonical_unlock_digest(&nonce, session, &pc_id, time);
        assert_eq!(d1, d2);

        // Modifying any parameter changes digest
        let d3 = canonical_unlock_digest(&nonce, "session-different", &pc_id, time);
        assert_ne!(d1, d3);

        let d4 = canonical_unlock_digest(&nonce, session, &DeviceId([8u8; 32]), time);
        assert_ne!(d1, d4);

        let d5 = canonical_unlock_digest(&[2u8; 32], session, &pc_id, time);
        assert_ne!(d1, d5);

        let d6 = canonical_unlock_digest(&nonce, session, &pc_id, time + 1);
        assert_ne!(d1, d6);
    }

    #[test]
    fn test_canonical_lock_digest_is_deterministic() {
        let pc_id = DeviceId([9u8; 32]);
        let nonce = [4u8; 32];
        let time = 1795160000u64;

        let d1 = canonical_lock_digest(&nonce, &pc_id, time);
        let d2 = canonical_lock_digest(&nonce, &pc_id, time);
        assert_eq!(d1, d2);

        let d3 = canonical_lock_digest(&nonce, &DeviceId([10u8; 32]), time);
        assert_ne!(d1, d3);
    }

    #[test]
    fn test_cbor_serialization_roundtrip() {
        let challenge = UnlockChallenge {
            nonce: vec![42u8; 32],
            session_id: "test-session-abc".into(),
            pc_id: DeviceId([1u8; 32]),
            expiry: 1795160030,
        };
        let mut buf = Vec::new();
        ciborium::into_writer(&challenge, &mut buf).unwrap();
        let decoded: UnlockChallenge = ciborium::from_reader(&buf[..]).unwrap();
        assert_eq!(challenge, decoded);

        let response = UnlockResponse {
            session_id: "test-session-abc".into(),
            timestamp: 1795160005,
            signature: vec![1, 2, 3, 4, 5],
        };
        buf.clear();
        ciborium::into_writer(&response, &mut buf).unwrap();
        let decoded_resp: UnlockResponse = ciborium::from_reader(&buf[..]).unwrap();
        assert_eq!(response, decoded_resp);
    }
}
